/**
 * 纯 JS SHA-256 实现（同步、零依赖）
 *
 * 为什么不用 crypto.subtle：它是异步 API，且我们不引入 Node crypto，
 * 保证 engine 在 浏览器 / 本地 server / 云函数 三端行为完全一致
 * （单一编译产物的正确性前提）。
 */

